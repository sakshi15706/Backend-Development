// Program 2: Insert documents (Create)
// Run:  node 2_insert.js

const { withDb, title, ObjectId } = require("./db");

withDb(async (db) => {
  const students = db.collection("students");
  await students.deleteMany({});                 // start empty so the program can be repeated
  await students.dropIndexes().catch(() => {});

  title("1. insertOne: add a single document");
  const one = await students.insertOne({
    name: "Rahul", roll: 101, course: "CSE", marks: 85, city: "Meerut",
    skills: ["html", "css"],
    createdAt: new Date()                        // time generated by the program
  });
  console.log("acknowledged:", one.acknowledged);
  console.log("insertedId  :", one.insertedId);  // _id is created by MongoDB
  console.log("Is it an ObjectId?", one.insertedId instanceof ObjectId);
  console.log("Time inside the id:", one.insertedId.getTimestamp());

  title("2. insertMany: add several documents together");
  const many = await students.insertMany([
    { name: "Priya", roll: 102, course: "CSE", marks: 92, city: "Delhi",  skills: ["js", "node"],  createdAt: new Date() },
    { name: "Amit",  roll: 103, course: "IT",  marks: 74, city: "Meerut", skills: ["python"],      createdAt: new Date() },
    { name: "Neha",  roll: 104, course: "IT",  marks: 66, city: "Noida",  skills: ["java", "sql"], createdAt: new Date() }
  ]);
  console.log("insertedCount:", many.insertedCount);
  console.log("insertedIds  :", many.insertedIds);

  title("3. A document can have its own _id");
  await students.insertOne({ _id: "custom-1", name: "Karan", roll: 105, course: "ECE", marks: 58, city: "Delhi", skills: ["c"] });
  console.log("Inserted a document with _id = 'custom-1'");

  title("4. Duplicate _id gives an error (code 11000)");
  try {
    await students.insertOne({ _id: "custom-1", name: "Copy" });
  } catch (err) {
    console.log("Error code   :", err.code);
    console.log("Error message:", err.message.split("\n")[0]);
  }

  title("5. Documents do not need the same fields (flexible schema)");
  await students.insertOne({ name: "Sneha", roll: 106, course: "CSE", marks: 88, hobbies: ["music"], address: { city: "Noida", pin: 201301 } });
  console.log("Inserted a document with different fields (hobbies, nested address)");

  title("6. Read everything back");
  const all = await students.find().toArray();
  console.log("Total documents:", all.length);
  all.forEach((s) => console.log(" ", s.roll, s.name, "-", s.course, "-", s.marks));
});
